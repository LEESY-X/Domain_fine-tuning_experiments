import ast
import json
import sys
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
errors = []

cfg = json.loads((ROOT / "config" / "experiment_config.json").read_text(encoding="utf-8"))
expected = ["full_ft", "lora", "adapter", "ia3", "bitfit"]
if cfg["methods"] != expected: errors.append(f"methods mismatch: {cfg['methods']}")
if cfg["seeds"] != [42, 52, 62, 72, 82]: errors.append(f"seeds mismatch: {cfg['seeds']}")
if cfg["study2"].get("limits") is not None: errors.append("study2 PAPER must use full original splits (limits=null)")

for path in sorted([*(ROOT / "src").glob("*.py"), *(ROOT / "tools").glob("*.py")]):
    try:
        ast.parse(path.read_text(encoding="utf-8"))
    except Exception as exc:
        errors.append(f"{path.relative_to(ROOT)}: {exc}")
for path in sorted((ROOT / "notebooks").glob("*.ipynb")):
    try:
        nb = json.loads(path.read_text(encoding="utf-8"))
        if nb.get("nbformat") != 4: errors.append(f"bad nbformat: {path.name}")
        for c in nb.get("cells", []):
            if c.get("cell_type") == "code": ast.parse("".join(c.get("source", [])))
    except Exception as exc:
        errors.append(f"{path.name}: {exc}")

# Local workflow notebooks are regenerated by tools/create_notebooks.py after
# stripping historical execution output and machine-local paths.  The two
# clean Colab runners are validated separately below.
expected_notebooks = {
    "00_precheck.ipynb",
    "01_study1_bertweet_hate.ipynb",
    "02_study2_multitask.ipynb",
    "03_study3_korean.ipynb",
    "04_aggregate.ipynb",
    "05_progress_monitor.ipynb",
}
actual_notebooks = {path.name for path in (ROOT / "notebooks").glob("*.ipynb")}
if actual_notebooks != expected_notebooks:
    errors.append(
        "local notebook set mismatch: "
        f"missing={sorted(expected_notebooks - actual_notebooks)}, "
        f"unexpected={sorted(actual_notebooks - expected_notebooks)}"
    )
for name in ("colab_a100_full_550_runs.ipynb", "colab_a100_low_drive_550_runs.ipynb"):
    path = ROOT / name
    if not path.exists():
        errors.append(f"missing public Colab notebook: {name}")
        continue
    try:
        notebook = json.loads(path.read_text(encoding="utf-8"))
        if notebook.get("nbformat") != 4:
            errors.append(f"bad nbformat: {name}")
        for cell in notebook.get("cells", []):
            if cell.get("cell_type") == "code":
                source = "".join(cell.get("source", []))
                # IPython magics are valid notebook syntax but not Python AST.
                python_source = "\n".join(
                    line for line in source.splitlines() if not line.lstrip().startswith(("%", "!"))
                )
                if python_source.strip():
                    ast.parse(python_source)
                if cell.get("outputs"):
                    errors.append(f"public notebook contains outputs: {name}")
                if cell.get("execution_count") is not None:
                    errors.append(f"public notebook has execution_count: {name}")
    except Exception as exc:
        errors.append(f"{name}: {exc}")

html_files = [
    ROOT / "experiment_design_visualization.html",
    ROOT / "paper_experiment_methodology_visualization.html",
    ROOT / "project_experiment_overview.html",
]
for path in html_files:
    if not path.exists():
        continue
    try:
        source = path.read_text(encoding="utf-8")
        HTMLParser().feed(source)
        for marker in ("550", "Full FT", "LoRA", "Adapter", "IA³", "BitFit"):
            if marker not in source: errors.append(f"{path.name}: missing {marker}")
        if any(stale in source for stale in ("Total: 625 runs", "Size sensitivity: 75 runs", "최대 50,000 train")):
            errors.append(f"{path.name}: stale experiment scope")
    except Exception as exc:
        errors.append(f"{path.name}: {exc}")

for study, count in (("study1", 25), ("study2", 450), ("study3", 75)):
    section = cfg[study]
    actual = len(section["tasks"]) * len(section["models"]) * len(cfg["methods"]) * len(cfg["seeds"])
    if actual != count: errors.append(f"{study}: expected {count}, got {actual}")

followup = json.loads((ROOT / "config" / "collapse_followup.json").read_text(encoding="utf-8"))
if followup["seeds"] != cfg["seeds"]: errors.append("follow-up seeds must match the main experiment seeds")
if len(followup["conditions"]) != 4: errors.append("follow-up must cover the four zero-SD conditions")
if "baseline" not in followup["variants"] or "higher_lr_weighted" not in followup["variants"]:
    errors.append("follow-up baseline/remedy variants missing")

try:
    import pandas as pd

    public_summary = pd.read_csv(ROOT / "final_tables" / "summary_by_task_model_method.csv", encoding="utf-8-sig")
    if len(public_summary) != 110: errors.append(f"public summary: expected 110 rows, got {len(public_summary)}")
    if int((public_summary["f1_sd"] == 0).sum()) != 4:
        errors.append("public summary: expected four exact-zero F1 SD rows")
except Exception as exc:
    errors.append(f"public summary validation: {exc}")

provenance_path = ROOT / "results" / "followup" / "provenance.json"
if provenance_path.exists():
    try:
        provenance = json.loads(provenance_path.read_text(encoding="utf-8"))
        for run_config in (ROOT / "results" / "followup").glob("collapse_followup_v2_*/**/run_config.json"):
            payload = json.loads(run_config.read_text(encoding="utf-8"))
            expected_revision = provenance["model_revisions"].get(payload["model"])
            if expected_revision != payload.get("model_commit"):
                errors.append(f"model revision mismatch: {run_config.relative_to(ROOT)}")
    except Exception as exc:
        errors.append(f"follow-up provenance validation: {exc}")

if errors:
    print("VALIDATION FAILED")
    print("\n".join(f"- {x}" for x in errors))
    sys.exit(1)
print("VALIDATION PASS")
print("study1=25, study2=450, study3=75 PAPER runs")
